// MARK: - CLI Tool Registry

/// Registry of available CLI coding agents
struct CLIToolRegistry {

    /// Known CLI tools that can be orchestrated
    enum Tool: String, CaseIterable, Identifiable, Codable {
        case codex = "codex"
        case claudeCLI = "claude"
        case copilotCLI = "gh-copilot"
        case geminiCLI = "gemini"
        case aiderCLI = "aider"
        case cursorCLI = "cursor"

        var id: String { rawValue }

        var displayName: String {
            switch self {
            case .codex: return "OpenAI Codex"
            case .claudeCLI: return "Claude CLI"
            case .copilotCLI: return "GitHub Copilot CLI"
            case .geminiCLI: return "Gemini CLI"
            case .aiderCLI: return "Aider"
            case .cursorCLI: return "Cursor CLI"
            }
        }

        var description: String {
            switch self {
            case .codex:
                return "OpenAI's code generation model optimized for programming tasks"
            case .claudeCLI:
                return "Anthropic's Claude assistant for code review and generation"
            case .copilotCLI:
                return "GitHub's AI assistant that provides command suggestions"
            case .geminiCLI:
                return "Google's Gemini CLI for code generation and analysis"
            case .aiderCLI:
                return "AI pair programming tool that edits code directly"
            case .cursorCLI:
                return "AI-first code editor with deep project understanding"
            }
        }

        var strengths: [String] {
            switch self {
            case .codex: return ["Fast", "Accurate", "Multi-language"]
            case .claudeCLI: return ["Code Review", "Context Understanding", "Python/JS Specialist"]
            case .copilotCLI: return ["Shell Integration", "Fast Suggestions", "Convenient"]
            case .geminiCLI: return ["Multi-modal", "High Context", "Fast Reasoning"]
            case .aiderCLI: return ["Project-wide Edits", "Git Integration", "Iterative Refinement"]
            case .cursorCLI: return ["Deep Context", "UI-first", "High Accuracy"]
            }
        }
    }

    /// Status of a CLI tool installation
    struct Availability: Identifiable, Codable {
        let tool: Tool
        var isInstalled: Bool
        var version: String?
        var binaryPath: String?

        var id: String { tool.id }
    }
}

// MARK: - Orchestration Messages

/// A message in the orchestration conversation
struct OrchestratorMessage: Identifiable, Codable {
    let id: UUID
    let role: Role
    let content: String
    let timestamp: Date
    var toolCall: ToolCallInfo?

    enum Role: String, Codable {
        case user
        case orchestrator // The local LLM
        case tool // Output from a CLI tool
        case system
    }

    init(role: Role, content: String, toolCall: ToolCallInfo? = nil) {
        self.id = UUID()
        self.role = role
        self.content = content
        self.timestamp = Date()
        self.toolCall = toolCall
    }
}

struct ToolCallInfo: Codable {
    let toolName: String
    let instruction: String
    var status: Status

    enum Status: String, Codable {
        case pending
        case executing
        case success
        case failed
    }
}

// MARK: - Orchestration Plan

/// A multi-step execution plan generated by the LLM
struct OrchestrationPlan: Codable {
    let taskDescription: String
    let reasoning: String
    let steps: [OrchestrationStep]
}

/// A single step in an execution plan
struct OrchestrationStep: Codable, Identifiable {
    var id: String { "\(order)-\(tool.rawValue)" }
    let order: Int
    let tool: CLIToolRegistry.Tool
    let instruction: String
    var output: String?
    var status: StepStatus = .pending

    enum StepStatus: String, Codable {
        case pending
        case running
        case completed
        case failed
        case skipped
    }
}

