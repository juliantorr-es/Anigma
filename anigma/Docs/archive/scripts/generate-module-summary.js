#!/usr/bin/env node
const fs = require('fs')
const path = require('path')

const repoRoot = path.resolve(process.cwd())
const sourcesDir = path.join(repoRoot, 'Sources')

if (!fs.existsSync(sourcesDir)) {
  console.error('Sources directory not found; run command from repo root via npm script')
  process.exit(1)
}

const moduleDirs = fs
  .readdirSync(sourcesDir)
  .filter((name) => {
    const candidate = path.join(sourcesDir, name)
    return fs.statSync(candidate).isDirectory()
  })
  .sort()

const modules = moduleDirs.map(moduleName => {
  const modulePath = path.join(sourcesDir, moduleName)
  const files = fs.readdirSync(modulePath)
  const lineCount = files.reduce((acc, file) => {
    const filePath = path.join(modulePath, file)
    if (fs.statSync(filePath).isFile()) {
      const fileContent = fs.readFileSync(filePath, 'utf-8')
      return acc + fileContent.split('\n').length
    }
    return acc
  }, 0)

  return {
    name: moduleName,
    path: path.join('Sources', moduleName),
    files: files,
    lineCount: lineCount
  }
})

const segments = modules.map((module) => {
  const description = `Generated module entry for ${module.name}`
  return `- **${module.name}** — ${description}. (See \`${module.path}\`.)`
})

const now = new Date()
const timestamp = now.toISOString()

const markdownOutput = `# Generated module index\n\nThis file is regenerated by \`npm run docs:sync\`.\n\n**Last verified**: ${timestamp}\n\n${segments.join('\n')}\n`

const jsonOutput = {
  lastVerified: timestamp,
  moduleCount: modules.length,
  modules: modules,
}

const outDir = path.join(repoRoot, 'Docs', 'automation')
if (!fs.existsSync(outDir)) {
  fs.mkdirSync(outDir, { recursive: true })
}

const markdownPath = path.join(outDir, 'ModuleSummary.md')
fs.writeFileSync(markdownPath, markdownOutput)
console.log('Updated', markdownPath)

const jsonPath = path.join(outDir, 'ModuleSummary.json')
fs.writeFileSync(jsonPath, JSON.stringify(jsonOutput, null, 2))
console.log('Updated', jsonPath)
